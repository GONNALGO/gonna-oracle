// Pre-rasterized glyphs: each is a flat list of [x,y] pixel offsets.
const GLYPHS = new Map<string, Uint8Array>();
for (const ch of Object.keys(GLYPH_ROWS)) {
  const rows = GLYPH_ROWS[ch];
  const pts: number[] = [];
  for (let y = 0; y < 7; y++) {
    for (let x = 0; x < 5; x++) {
      if (rows[y].charCodeAt(x) === 49) pts.push(x, y);
    }
  }
  GLYPHS.set(ch, new Uint8Array(pts));
}

export type Align = 'left' | 'center' | 'right';

export function textWidth(str: string, scale: number): number {
  return str.length * 6 * scale - scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  scale: number,
  color: string,
  align: Align = 'left',
): void {
  const s = str.toUpperCase();
  let ox = Math.round(x);
  const oy = Math.round(y);
  if (align === 'center') ox -= Math.floor(textWidth(s, scale) / 2);
  else if (align === 'right') ox -= textWidth(s, scale);
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS.get(s[i]);
    if (!g) continue;
    const gx = ox + i * 6 * scale;
    for (let p = 0; p < g.length; p += 2) {
      ctx.fillRect(gx + g[p] * scale, oy + g[p + 1] * scale, scale, scale);
    }
  }
}

// Text with a dark drop shadow (arcade look).
export function drawTextSh(
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  scale: number,
  color: string,
  align: Align = 'left',
  shadow = '#0a0a12',
): void {
  drawText(ctx, str, x + scale, y + scale, scale, shadow, align);
  drawText(ctx, str, x, y, scale, color, align);
}
